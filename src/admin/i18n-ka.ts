type Dict = Record<string, unknown>
function merge(base: Dict, over: Dict): Dict {
  const out: Dict = { ...base }
  for (const [k, v] of Object.entries(over)) out[k] = v && typeof v === 'object' ? merge((base[k] as Dict) || {}, v as Dict) : v
  return out
}

